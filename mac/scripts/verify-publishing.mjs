import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root=resolve(fileURLToPath(new URL("../",import.meta.url)),"..");
const read=p=>readFile(resolve(root,p),"utf8");
const [main,api,upload,ui,pkg]=await Promise.all(["mac/main.mjs","mac/publishing-history.mjs","mac/youtube-upload.mjs","worker/index.js","mac/package.json"].map(read));
const config=JSON.parse(pkg);
assert(config.build.files.includes("publishing-history.mjs"));
assert(main.includes("await handlePublishing(incoming, outgoing, requestUrl)"));
assert(main.includes("allowedLocalRequest("),"Publishing endpoints must remain behind session token auth");
assert(api.includes('"/api/publishing/history"')&&api.includes('"/api/publishing/sync"')&&api.includes('"/api/publishing/schedule"'));
assert(api.includes('privacyStatus:"private",publishAt:'),"Schedule must keep video private until publish");
assert(api.includes('Date.now()+5*60*1000'),"Reject past/immediate release dates");
assert(api.includes("fetchVideo(id,auth)"),"Verify target video belongs to active channel");
assert(api.includes("channelId!==auth.channelId"));
assert(api.includes("await rename(tmp,file())"),"Write history atomically");
assert(api.includes("channelId:channel.channelId"),"Track channel identity for every video");
assert(upload.includes("youtube.force-ssl"),"Reauthorization must include edit scope");
assert(upload.includes("safeStorage.encryptString("),"Keep all channel refresh tokens encrypted");
assert(upload.includes('"/api/youtube/switch"'),"Multiple channel authorization required");
assert(ui.includes('id="publishingTracker"')&&ui.includes('id="publishingSchedule"'));
assert(ui.includes('id="publishingChannelFilter"')&&ui.includes('id="youtubeActiveChannel"'));
assert(ui.includes('await api("/api/publishing/schedule"'),"UI must schedule via YouTube API");
console.log("Clip Farm publishing dashboard static checks passed.");
