import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root=resolve(fileURLToPath(new URL("../",import.meta.url)),"..");
const read=path=>readFile(resolve(root,path),"utf8");
const [worker,upload,main,pkg]=await Promise.all([read("worker/index.js"),read("mac/youtube-upload.mjs"),read("mac/main.mjs"),read("mac/package.json")]);
const packageJson=JSON.parse(pkg);
assert(packageJson.build.files.includes("youtube-upload.mjs"),"YouTube uploader must be packaged in Mac app");
assert(main.includes('await handleYouTube(incoming,outgoing'),"Mac desktop must route local YouTube endpoints");
assert(main.includes("await restoreYouTubeConnection()"),"Mac must restore encrypted OAuth tokens on startup");
assert(upload.includes('privacyStatus:"unlisted"'),"Every direct YouTube upload must request Unlisted visibility");
assert(upload.includes("snippet:{title,description,tags"),"Video SEO including keyword tags must be uploaded in the same request");
assert(upload.includes('if(input.visibility!=="unlisted")'),"Direct YouTube upload must reject non-Unlisted requests");
assert(upload.includes("verifyRevidVideo(pid,key)"),"Revid project ID must be verified via Revid API");
assert(upload.includes("safeStorage.encryptString("), "Google credentials must be encrypted at rest");
assert(upload.includes('await rememberConnection()'),"Google authorization must persist after consent");
assert(upload.includes('channels?part=snippet&mine=true'),"Identify authorized YouTube channel");
assert(upload.includes('videos?part=status&id='),"Verify actual YouTube privacy after upload");
assert(worker.includes('data-unlisted-upload='),"Existing/new jobs need direct upload action");
assert(worker.includes('id="youtubeUploadAll"'),"Need bulk uploads without manual individual uploads");
assert(worker.includes('id="newGenerateAllSeo"'),"Need SEO generation for new Revid renders");
assert(worker.includes('batchJobs.some(other=>other!==j&&other.pid===j.pid'),"Prevent double uploads for same Revid project ID");
assert(worker.includes('if($("youtubeVisibility").value!=="public")'),"Revid Public publishing must remain explicitly gated");
assert(worker.includes('if(!skipConfirmation&&!confirm('),"Batch Unlisted uploads should not prompt every video");
console.log("Clip Farm unlisted pipeline static checks passed.");
